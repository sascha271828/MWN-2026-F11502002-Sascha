#!/usr/bin/env python3
"""
Verify the XR traffic model generated by XrTrafficApp against its analytical
definition (3GPP TR 26.926 cl. 6.5.3 / TR 38.838) and plot the network delay.

Reads <results>/config.txt and the CSV traces written by xr-wifi.cc, then writes
into <results>/plots/:
  frame_size.pdf      PDF + CDF of the frame size, model overlay
  jitter.pdf          PDF + CDF of the jitter (actual minus nominal time)
  inter_arrival.pdf   PDF + CDF of the frame inter-arrival time, model overlay
  packet_size.pdf     PMF + CDF of the UDP payload size, model overlay
  delay_cdf.pdf       CDF of the per packet one way delay (receiver side)
  stats.md            model vs measured statistics incl. KS tests

Usage:
  python3 plot_distributions.py --results a2-results [--flow dl_sta0]
"""

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats

plt.rcParams.update({"figure.dpi": 150, "font.size": 10, "axes.titleweight": "bold"})
C_EMP, C_MOD = "#4C72B0", "#DD8452"


# ------------------------------------------------------------------ helpers
def read_config(path: Path) -> dict:
    cfg = {}
    for line in path.read_text().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            try:
                cfg[k] = float(v)
            except ValueError:
                cfg[k] = v
    return cfg


def truncnorm(mean, std, bound):
    """Symmetric truncated normal, same definition as ns-3 NormalRandomVariable+Bound."""
    a = -bound / std
    return stats.truncnorm(a, -a, loc=mean, scale=std)


def ecdf(x):
    x = np.sort(np.asarray(x))
    return x, np.arange(1, len(x) + 1) / len(x)


def pdf_cdf_figure(data, x_model, pdf_model, cdf_model, xlabel, title, out, bins=60):
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4))
    a1.hist(data, bins=bins, density=True, color=C_EMP, alpha=0.7, edgecolor="white",
            label=f"simulated (n={len(data)})")
    a1.plot(x_model, pdf_model, color=C_MOD, lw=2, ls="--", label="model")
    a1.set(xlabel=xlabel, ylabel="PDF", title=f"{title}: PDF")
    a1.legend()
    xs, ys = ecdf(data)
    a2.step(xs, ys, where="post", color=C_EMP, lw=2, label="simulated (ECDF)")
    a2.plot(x_model, cdf_model, color=C_MOD, lw=2, ls="--", label="model")
    a2.set(xlabel=xlabel, ylabel="CDF", title=f"{title}: CDF", ylim=(0, 1.02))
    a2.legend(loc="lower right")
    for a in (a1, a2):
        a.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def ks_numeric(data, x_grid, cdf_grid):
    """KS statistic against a CDF given on a grid (for the convolution model)."""
    xs, ys = ecdf(data)
    model = np.interp(xs, x_grid, cdf_grid)
    d = max(np.max(np.abs(ys - model)), np.max(np.abs(ys - 1 / len(xs) - model)))
    return d, stats.kstwo.sf(d, len(xs))


# ------------------------------------------------------------------ main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="a2-results")
    ap.add_argument("--flow", default="dl_sta0", help="XR video flow to verify")
    args = ap.parse_args()

    res = Path(args.results)
    out = res / "plots"
    out.mkdir(exist_ok=True)
    cfg = read_config(res / "config.txt")
    frames = pd.read_csv(res / "tx_frames.csv")
    txp = pd.read_csv(res / "tx_packets.csv")
    rxp = pd.read_csv(res / "rx_packets.csv")

    f = frames[frames.flow == args.flow].sort_values("time_s")
    p = txp[txp.flow == args.flow]

    # ---- model parameters
    M = cfg["meanSize"]
    s_std, s_bnd = M * cfg["sizeStdPct"] / 100, M * cfg["sizeBoundPct"] / 100
    j_std, j_bnd = cfg["jitterStd"], cfg["jitterMax"]
    T = 1e3 / (cfg["fps"] * cfg["eyeBuffers"])  # nominal period [ms]
    P = int(cfg["maxPayload"])
    size_rv = truncnorm(M, s_std, s_bnd)
    jit_rv = truncnorm(0.0, j_std, j_bnd)

    rows = []  # (quantity, statistic, model, measured)

    # ---- 1) frame size
    x = np.linspace(M - s_bnd, M + s_bnd, 600)
    pdf_cdf_figure(f.size_B, x, size_rv.pdf(x), size_rv.cdf(x), "frame size [byte]",
                   "Frame size", out / "frame_size.pdf")
    ks_s = stats.kstest(f.size_B, size_rv.cdf)
    rows += [("frame size [B]", "mean", size_rv.mean(), f.size_B.mean()),
             ("frame size [B]", "std", size_rv.std(), f.size_B.std()),
             ("frame size [B]", "min", M - s_bnd, f.size_B.min()),
             ("frame size [B]", "max", M + s_bnd, f.size_B.max()),
             ("frame size [B]", "KS D (p)", np.nan, f"{ks_s.statistic:.4f} ({ks_s.pvalue:.2f})")]

    # ---- 2) jitter = actual - nominal
    jit = (f.time_s - f.nominal_s) * 1e3
    xj = np.linspace(-j_bnd, j_bnd, 600)
    pdf_cdf_figure(jit, xj, jit_rv.pdf(xj), jit_rv.cdf(xj), "jitter [ms]", "Jitter",
                   out / "jitter.pdf")
    ks_j = stats.kstest(jit, jit_rv.cdf)
    rows += [("jitter [ms]", "mean", 0.0, jit.mean()),
             ("jitter [ms]", "std", jit_rv.std(), jit.std()),
             ("jitter [ms]", "KS D (p)", np.nan, f"{ks_j.statistic:.4f} ({ks_j.pvalue:.2f})")]

    # ---- 3) frame inter-arrival = T + (J_k - J_{k-1}); pdf = f_J convolved with f_J
    ia = np.diff(f.time_s.values) * 1e3
    dx = 0.001
    g = np.arange(-j_bnd, j_bnd + dx, dx)
    conv = np.convolve(jit_rv.pdf(g), jit_rv.pdf(g)[::-1]) * dx  # pdf of J1 - J2
    xd = np.arange(len(conv)) * dx - 2 * j_bnd + T
    cdf_d = np.clip(np.cumsum(conv) * dx, 0, 1)
    pdf_cdf_figure(ia, xd, conv, cdf_d, "inter-arrival time [ms]", "Frame inter-arrival",
                   out / "inter_arrival.pdf")
    d_ia, p_ia = ks_numeric(ia, xd, cdf_d)
    rows += [("inter-arrival [ms]", "mean", T, ia.mean()),
             ("inter-arrival [ms]", "std", np.sqrt(2) * jit_rv.std(), ia.std()),
             ("inter-arrival [ms]", "KS D (p)", np.nan, f"{d_ia:.4f} ({p_ia:.2f})")]

    # ---- 4) packet (UDP payload) size, model derived by fragmenting the frame size pdf
    s = np.arange(int(np.ceil(M - s_bnd)), int(np.floor(M + s_bnd)) + 1)
    w = size_rv.pdf(s)
    w /= w.sum()
    pmf, n_mean = {}, 0.0
    for si, wi in zip(s, w):
        n = -(-si // P)
        n_mean += wi * n
        pmf[P] = pmf.get(P, 0) + wi * (n - 1)
        last = max(si - (n - 1) * P, 16)
        pmf[last] = pmf.get(last, 0) + wi
    ks_sizes = np.array(sorted(pmf))
    mod_pmf = np.array([pmf[k] for k in ks_sizes])
    mod_pmf /= mod_pmf.sum()

    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4))
    bins = np.linspace(0, P + 50, 70)
    a1.hist(p.size_B, bins=bins, weights=np.ones(len(p)) / len(p), color=C_EMP, alpha=0.7,
            edgecolor="white", label=f"simulated (n={len(p)})")
    mod_hist, _ = np.histogram(ks_sizes, bins=bins, weights=mod_pmf)
    a1.step(bins[:-1], mod_hist, where="post", color=C_MOD, lw=2, ls="--", label="model")
    a1.set(xlabel="UDP payload size [byte]", ylabel="probability (log)", yscale="log",
           title="Packet size: PMF")
    a1.legend(loc="upper left")
    xs, ys = ecdf(p.size_B)
    a2.step(xs, ys, where="post", color=C_EMP, lw=2, label="simulated (ECDF)")
    a2.step(ks_sizes, np.cumsum(mod_pmf), where="post", color=C_MOD, lw=2, ls="--",
            label="model")
    a2.set(xlabel="UDP payload size [byte]", ylabel="CDF", title="Packet size: CDF",
           ylim=(0, 1.02))
    a2.legend(loc="upper left")
    for a in (a1, a2):
        a.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out / "packet_size.pdf", bbox_inches="tight")
    plt.close(fig)
    rows += [("packet size [B]", f"share of {P} B", pmf[P] / sum(pmf.values()),
              (p.size_B == P).mean()),
             ("packets per frame", "mean", n_mean,
              len(p) / len(f))]

    # ---- 5) receiver side delay per flow
    fig, ax = plt.subplots(figsize=(6, 4))
    for i, (name, grp) in enumerate(rxp.groupby("flow")):
        xs, ys = ecdf(grp.delay_ms)
        ax.step(xs, ys, where="post", lw=2, label=name,
                ls=["-", "--", ":", "-."][i % 4])
        rows += [(f"delay {name} [ms]", "mean / p95 / max", np.nan,
                  f"{grp.delay_ms.mean():.3f} / {grp.delay_ms.quantile(0.95):.3f} / "
                  f"{grp.delay_ms.max():.3f}")]
    ax.set(xscale="log", xlabel="one way delay [ms] (log)", ylabel="CDF",
           title="Per packet delay (app to app)", ylim=(0, 1.02))
    ax.legend(loc="lower right")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out / "delay_cdf.pdf", bbox_inches="tight")
    plt.close(fig)

    # ---- stats table
    def fmt(v):
        return "" if isinstance(v, float) and np.isnan(v) else (
            f"{v:.4g}" if isinstance(v, (float, np.floating)) else str(v))

    lines = ["| quantity | statistic | model | measured |", "| :--- | :--- | ---: | ---: |"]
    lines += [f"| {q} | {s_} | {fmt(m)} | {fmt(v)} |" for q, s_, m, v in rows]
    table = "\n".join(lines)
    (out / "stats.md").write_text(
        f"Flow `{args.flow}`, config: R={cfg['rateMbps']} Mbit/s, F={cfg['fps']} fps, "
        f"E={int(cfg['eyeBuffers'])}, run={int(cfg['run'])}\n\n{table}\n")
    print(table)
    print(f"\nPlots written to {out}/")


if __name__ == "__main__":
    main()